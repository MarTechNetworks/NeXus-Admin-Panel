// ── Decoded account shapes (camelCase — see the header note) ─────────────────

/** Anchor decodes u64/i64 to BN; we only ever need toString()/toNumber(). */
export interface Bnish {
  toString(radix?: number): string
  toNumber(): number
}

export interface RegistryAccount {
  authority: PublicKey
  pendingAuthority: PublicKey | null
  pendingUpgradeProgram: PublicKey
  upgradeInitiatedTime: Bnish
  upgradeCompletionTime: Bnish
  emergencyPauseTime: Bnish
  collections: PublicKey[]
  collectionCount: number
  upgradeState: number
  emergencyPause: boolean
  bump: number
}

export interface PlatformFeeConfigAccount {
  recipients: PublicKey[]
  /** Flat platform fee per NFT, lamports. Copied into each collection at creation. */
  feeLamports: Bnish
  sharesBps: number[]
  num: number
  bump: number
}

export interface CollectionAccount {
  authority: PublicKey
  mint: PublicKey
  mintAuthority: PublicKey
  creatorWallet: PublicKey
  platformWallet: PublicKey
  maxSupply: Bnish
  minted: Bnish
  price: Bnish
  startTime: Bnish
  endTime: Bnish
  freezeUntil: Bnish
  createdAt: Bnish
  /** Flat platform fee per NFT, lamports — frozen at create_collection. */
  platformFeeLamports: Bnish
  allowlistRoot: number[]
  mintLimitPerWallet: number
  metadataStandard: number
  flags: number
  status: number
  featured: boolean
  bump: number
  metadataUri: string
}

/**
 * `program.account` is typed against a generic Idl, so the named accounts are not
 * known statically. This narrows it to the three we read, in one place, instead
 * of casting at every call site.
 */
interface AccountNamespace {
  collectionRegistry: {
    fetchNullable(address: PublicKey): Promise<RegistryAccount | null>
  }
  platformFeeConfig: {
    fetchNullable(address: PublicKey): Promise<PlatformFeeConfigAccount | null>
  }
  collection: {
    fetchNullable(address: PublicKey): Promise<CollectionAccount | null>
  }
}

export function accounts(program: Program): AccountNamespace {
  return program.account as unknown as AccountNamespace
}

/**
 * Decode one raw Collection account. Throws on a layout mismatch — the caller
 * decides whether that is fatal. Anchor's own `fetchMultiple` decodes the whole
 * batch in one go, so a single pre-redeploy account would sink every collection
 * with it; decoding one at a time is what lets the console keep rendering.
 */
export function decodeCollection(program: Program, data: Buffer): CollectionAccount {
  // `data` is whatever web3.js handed back from getMultipleAccountsInfo — already
  // a Buffer built by its own bundled `buffer`, so no Node global is touched here.
  return program.coder.accounts.decode<CollectionAccount>('collection', data)
}
