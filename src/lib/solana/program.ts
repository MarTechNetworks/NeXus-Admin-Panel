/**
 * program.ts — IDL-driven access to nexus_launchpad from the admin console.
 *
 * One casing rule, and it matters: `new Program(idl)` converts the whole IDL to
 * camelCase, so every method, account name and struct field goes through the
 * client as camelCase (`updatePlatformFeeConfig`, `registry.emergencyPause`,
 * `{ core: {} }` for enum variants). Passing snake_case keys does NOT throw —
 * anchor's layout silently encodes zeros for the fields it cannot find, which
 * produces a well-formed transaction that sets everything to 0. Build args
 * through `program.methods.*` and read accounts through `program.account.*` and
 * that trap stays shut.
 *
 * The IDL is a copy of Frontend/lib/solana/idl/nexus_launchpad.json, itself
 * generated by programs/scripts/build-deploy.sh. Keep this the only module in
 * the admin app that imports it.
 */
import { AnchorProvider, Program, type Idl } from '@coral-xyz/anchor'
import { Connection, PublicKey } from '@solana/web3.js'
import idlJson from './idl/nexus_launchpad.json'

/** A wallet that signs nothing — Program is only ever used to BUILD instructions. */
const NOOP_WALLET = {
  publicKey: PublicKey.default,
  signTransaction: async <T>(tx: T) => tx,
  signAllTransactions: async <T>(txs: T[]) => txs,
}

/**
 * An anchor Program bound to `connection`, targeting `programId` from
 * GET /api/solana/config rather than whatever address the committed IDL carries
 * (the IDL lags a redeploy; the backend never does).
 */
export function getProgram(connection: Connection, programId?: PublicKey | string): Program {
  const provider = new AnchorProvider(connection, NOOP_WALLET as never, { commitment: 'confirmed' })
  const idl: Idl = programId
    ? { ...(idlJson as Idl), address: typeof programId === 'string' ? programId : programId.toBase58() }
    : (idlJson as Idl)
  return new Program(idl, provider)
}

// ── PDAs ─────────────────────────────────────────────────────────────────────
// Seeds must match programs/programs/nexus-launchpad/src/lib.rs exactly.
// Encoded as Uint8Array rather than Buffer so nothing here depends on a Node
// global being polyfilled into the browser bundle.

const seed = (text: string) => new TextEncoder().encode(text)

export const REGISTRY_SEED = seed('registry')
export const PLATFORM_FEE_CONFIG_SEED = seed('platform_fee_config')
export const COLLECTION_SEED = seed('collection')

export function deriveRegistryPda(programId: PublicKey): PublicKey {
  return PublicKey.findProgramAddressSync([REGISTRY_SEED], programId)[0]
}

export function derivePlatformFeeConfigPda(programId: PublicKey): PublicKey {
  return PublicKey.findProgramAddressSync([PLATFORM_FEE_CONFIG_SEED], programId)[0]
}

export function deriveCollectionPda(mintSeed: PublicKey, programId: PublicKey): PublicKey {
  return PublicKey.findProgramAddressSync([COLLECTION_SEED, mintSeed.toBuffer()], programId)[0]
}

